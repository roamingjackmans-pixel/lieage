// Builds public/js/prompts.js from the question files in data/prompts/*.json, checking every question.
//   node tools/build-prompts.mjs          build (fails on a broken question)
//   node tools/build-prompts.mjs --check  only check, and fail if prompts.js is out of date
//
// A question file is a JSON array of
//   { id, topic, q, a, alt: [], d: [3 decoys], x: 0|1, src }
// q has exactly one _____ where the answer goes. x: 1 keeps it out of family-friendly games. src (where the
// fact comes from) stays in the data files and isn't shipped.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { isTruth, same, LIE_MAX } from '../public/js/engine.js';
import { CATS } from '../public/js/looks.js';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const dataDir = path.join(root, 'data', 'prompts');
const out = path.join(root, 'public', 'js', 'prompts.js');
const check = process.argv.includes('--check');

const problems = [];
const prompts = [];
const ids = new Set();
const seenQ = new Map();
const files = fs.readdirSync(dataDir).filter(f => f.endsWith('.json')).sort();
for (const f of files) {
  const c = path.basename(f, '.json');
  if (!CATS[c]) problems.push(`${f}: unknown category "${c}" (add it to CATS in public/js/looks.js)`);
  let list;
  try { list = JSON.parse(fs.readFileSync(path.join(dataDir, f), 'utf8')); } catch (e) { problems.push(`${f}: not valid JSON (${e.message})`); continue; }
  if (!Array.isArray(list)) { problems.push(`${f}: should be a JSON array`); continue; }
  for (const p of list) {
    const where = `${f} ${p && p.id ? p.id : '(no id)'}`;
    const bad = msg => problems.push(`${where}: ${msg}`);
    if (!p || typeof p !== 'object') { bad('not an object'); continue; }
    if (!p.id || typeof p.id !== 'string') bad('missing id');
    else if (ids.has(p.id)) bad('duplicate id');
    ids.add(p.id);
    const q = String(p.q || '').trim();
    const blanks = q.split('_____').length - 1;
    if (blanks !== 1) bad(`needs exactly one _____ (has ${blanks})`);
    if (/_{6,}/.test(q)) bad('blank should be exactly five underscores');
    const a = String(p.a || '').trim();
    if (!a) bad('missing answer');
    if (a.length > LIE_MAX) bad(`answer longer than ${LIE_MAX} characters`);
    const t = String(p.topic || '').trim();
    if (!t) bad('missing topic');
    if (t && a && same(t, a)) bad('topic gives away the answer');
    const d = Array.isArray(p.d) ? p.d.map(x => String(x).trim()).filter(Boolean) : [];
    if (d.length < 2) bad('needs at least 2 decoys');
    const alt = Array.isArray(p.alt) ? p.alt.map(x => String(x).trim()).filter(Boolean) : [];
    for (const x of d) if (isTruth({ a, alt }, x)) bad(`decoy "${x}" counts as the real answer`);
    const key = q.toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();
    if (seenQ.has(key)) bad(`same question as ${seenQ.get(key)}`);
    seenQ.set(key, p.id);
    const item = { id: p.id, c, t, q, a, d };
    if (alt.length) item.alt = alt;
    if (p.x) item.x = 1;
    prompts.push(item);
  }
}

if (problems.length) {
  console.error(`${problems.length} problem(s) in the questions:\n  ` + problems.join('\n  '));
  process.exit(1);
}

const counts = {};
for (const p of prompts) counts[p.c] = (counts[p.c] || 0) + 1;
const body = `// Generated by tools/build-prompts.mjs from data/prompts/*.json. Edit those files, not this one.\n` +
  `// ${prompts.length} questions: ${Object.entries(counts).map(([c, n]) => `${c} ${n}`).join(', ')}.\n` +
  `export const PROMPTS = [\n${prompts.map(p => '  ' + JSON.stringify(p)).join(',\n')}\n];\n`;

if (check) {
  const cur = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (cur !== body) { console.error('public/js/prompts.js is out of date: run node tools/build-prompts.mjs'); process.exit(1); }
  console.log(`questions ok: ${prompts.length}`);
} else {
  fs.writeFileSync(out, body);
  console.log(`wrote public/js/prompts.js: ${prompts.length} questions (${Object.entries(counts).map(([c, n]) => `${c} ${n}`).join(', ')}; family-friendly ${prompts.filter(p => !p.x).length})`);
}
